#!/usr/bin/env node
// 產生瀏覽器擴充所需的檔案：
//   1. extension/terms-data.js（由 data/*.json 打包）
//   2. extension/vendor/opencc.js + OPENCC-LICENSE（opencc-js UMD）
//   3. extension/vendor/epub-core.js（根目錄的共用核心）
// 用法：node tools/build-extension.mjs [--check]
//   --check 不寫入檔案，只檢查現有檔案是否與來源一致（CI 用）。

import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = path.join(ROOT, 'extension');
const checkOnly = process.argv.includes('--check');

const exists = async p => { try { await access(p); return true; } catch (e) { return false; } };
const stale = [];
const written = [];
const skipped = [];

function jsStringSafe(json) {
  // U+2028/U+2029 在舊版 JS 字串中不合法，跳脫以求保險
  return json.split(String.fromCharCode(0x2028)).join('\\u2028')
             .split(String.fromCharCode(0x2029)).join('\\u2029');
}

async function sync(dest, content, label) {
  const rel = path.relative(ROOT, dest);
  if (checkOnly) {
    let current = null;
    try { current = await readFile(dest); } catch (e) {}
    if (!current || !current.equals(Buffer.from(content))) stale.push(rel + (label ? `（${label}）` : ''));
    return;
  }
  await mkdir(path.dirname(dest), { recursive: true });
  await writeFile(dest, content);
  written.push(rel);
}

async function syncFromSource(src, dest, label) {
  if (!(await exists(src))) {
    if (checkOnly) { skipped.push(path.relative(ROOT, src)); return; }
    throw new Error(`找不到來源檔案：${path.relative(ROOT, src)}（請先執行 npm install）`);
  }
  await sync(dest, await readFile(src), label);
}

async function buildTermsData() {
  const indexPath = path.join(ROOT, 'data', 'index.json');
  const index = JSON.parse(await readFile(indexPath, 'utf8'));
  if (!Array.isArray(index.files) || !index.files.length) throw new Error('data/index.json 缺少 files 清單');
  const files = [];
  for (const file of index.files) {
    const d = JSON.parse(await readFile(path.join(ROOT, 'data', file), 'utf8'));
    files.push({ file, category: d.category, terms: d.terms || [] });
  }
  const payload = { version: index.version || '', files };
  return '/* Generated by tools/build-extension.mjs from data/*.json — do not edit. */\n' +
    'globalThis.JFT_TERMS = ' + jsStringSafe(JSON.stringify(payload)) + ';\n';
}

async function main() {
  const terms = await buildTermsData();
  await sync(path.join(EXT, 'terms-data.js'), terms, '詞彙資料');
  await syncFromSource(
    path.join(ROOT, 'node_modules', 'opencc-js', 'dist', 'umd', 'full.js'),
    path.join(EXT, 'vendor', 'opencc.js'), 'opencc-js UMD');
  await syncFromSource(
    path.join(ROOT, 'node_modules', 'opencc-js', 'LICENSE'),
    path.join(EXT, 'vendor', 'OPENCC-LICENSE'), 'opencc-js 授權');
  await syncFromSource(
    path.join(ROOT, 'epub-core.js'),
    path.join(EXT, 'vendor', 'epub-core.js'), '共用核心');

  if (checkOnly) {
    if (skipped.length) console.log(`略過（來源不存在，未安裝依賴）：${skipped.map(s => path.relative(ROOT, s)).join('、')}`);
    if (stale.length) {
      console.error('擴充產物已過期，請執行 npm run build:ext：');
      for (const f of stale) console.error('  ✘ ' + f);
      process.exit(1);
    }
    console.log('擴充產物是最新的。');
    return;
  }
  console.log(`已更新 ${written.length} 個檔案：`);
  for (const f of written) console.log('  ✔ ' + f);
}

main().catch(e => { console.error(e.message || e); process.exit(1); });
